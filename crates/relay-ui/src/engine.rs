//! Port between the desktop host and the engine. The real adapter wraps
//! `relay_api::RelayClient`; tests plug in a fake.

use std::sync::Arc;

use async_trait::async_trait;
use relay_api::WatchItem;
use relay_api::pb;

use relay_client::{ChannelOptions, Secret};

use crate::model::{Advert, ConnectionView, Inbound, Mode};
use crate::tr;

/// Why an engine request failed. `Rejected` carries the engine's own text,
/// shown as received; the other variants are worded by the UI.
#[derive(Debug)]
pub enum EngineError {
	/// Daemon not reachable (not running, socket missing, connection refused).
	Unavailable(String),
	/// The engine refused or failed the request.
	Rejected {
		code: String,
		message: String,
	},
	Timeout,
	/// The connection broke or violated the protocol; reconnect and resync.
	Broken(String),
	/// The background service runs but is not ready: it waits for the system's secure storage
	/// (a permission prompt) or failed to open it. Not an error to show as one.
	Starting(crate::model::Startup),
}

impl std::fmt::Display for EngineError {
	fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
		match self {
			Self::Unavailable(why) => {
				f.write_str(&tr!("err-daemon-unreachable", reason = why.as_str()))
			}
			Self::Rejected { message, .. } => f.write_str(plain_refusal(message)),
			Self::Timeout => f.write_str(tr!("err-engine-timeout")),
			Self::Broken(why) => f.write_str(&tr!("err-connection", reason = why.as_str())),
			Self::Starting(_) => f.write_str(tr!("startup-waiting-title")),
		}
	}
}

impl std::error::Error for EngineError {}

/// The engine words a refusal of bad input as `invalid: <reason>`; people read only the reason.
/// This is the one place the prefix is dropped.
pub fn plain_refusal(message: &str) -> &str {
	let message = message.trim();
	message.strip_prefix("invalid: ").unwrap_or(message)
}

/// Everything the UI may ask the engine to do. Ids are raw bytes already
/// validated by the controller; operation ids are generated by the adapter.
#[derive(Debug, Clone, PartialEq)]
pub enum Command {
	StartCall {
		peer_id: Vec<u8>,
	},
	AcquireController {
		call_id: Vec<u8>,
	},
	AcceptCall {
		call_id: Vec<u8>,
		generation: u64,
	},
	DeclineCall {
		call_id: Vec<u8>,
		generation: u64,
	},
	EndCall {
		call_id: Vec<u8>,
		generation: u64,
	},
	SetTransmit {
		call_id: Vec<u8>,
		generation: u64,
		mode: Mode,
	},
	SetCallControls {
		call_id: Vec<u8>,
		generation: u64,
		muted: Option<bool>,
		deafened: Option<bool>,
		receive_gain: Option<f32>,
	},
	SetGlobalControls {
		muted: Option<bool>,
		deafened: Option<bool>,
		microphone_gain: Option<f32>,
		playback_gain: Option<f32>,
		ptt_release_delay_ms: Option<u32>,
	},
	/// Ring, ringback and call-sound preferences; `None` is unchanged.
	SetRingPreferences {
		ringtone_enabled: Option<bool>,
		ringtone_volume: Option<f32>,
		ringback_enabled: Option<bool>,
		call_sounds_enabled: Option<bool>,
	},
	/// Play the ring on the daemon's own output for about two seconds.
	PreviewTone,
	/// Use an audio file as this device's incoming-call ringtone.
	SetRingtone {
		file_name: String,
		data: Vec<u8>,
	},
	/// Go back to the built-in ring.
	ResetRingtone,
	/// Whether the app starts the daemon by itself (stored by the daemon).
	SetAutostart {
		enabled: bool,
	},
	SelectDevices {
		input_id: String,
		output_id: String,
	},
	SetProfile {
		display_name: String,
	},
	UploadAvatar {
		bytes: Vec<u8>,
		media_type: String,
	},
	/// Remove the stored avatar; trusted peers stop showing it.
	ClearAvatar,
	/// Remove the stored trust decision for a peer (32 bytes) and cut the link.
	ForgetPeer {
		peer_id: Vec<u8>,
	},
	/// Replace the pinned key of a contact whose key changed by the key it presents now
	/// (`peer_id`, 32 bytes), after the user typed its full fingerprint from the other device.
	ReplacePinnedKey {
		peer_id: Vec<u8>,
		fingerprint: String,
	},
	/// Switch auto-answer for one contact (32 bytes). The engine refuses to switch it on for a
	/// contact that is not verified.
	SetPeerAutoAnswer {
		peer_id: Vec<u8>,
		enabled: bool,
	},
	/// Replace the favorites by this ordered list of trusted peers (32 bytes each, first =
	/// place 0). More than 6, a repeat or an untrusted peer is refused by the engine.
	SetFavorites {
		peer_ids: Vec<Vec<u8>>,
	},
	/// Trust a found device (32 byte key digest) after the user compared its
	/// fingerprint. The digest is also the key the engine must see.
	TrustPeer {
		peer_id: Vec<u8>,
	},
	/// Block a device (32 byte key digest): its calls and links are refused silently. A
	/// stored contact is forgotten with it. Unblocking is `ForgetPeer` on the same id.
	BlockPeer {
		peer_id: Vec<u8>,
	},
	/// Dial a scanned `relay://` string and trust the device as verified when its key matches
	/// the scanned fingerprint (the QR code is the out-of-band check).
	ConnectAndTrust {
		text: String,
	},
	/// Call a pasted `relay://` string; the engine validates it.
	StartCallConnection {
		text: String,
	},
	CreateChannel {
		name: String,
		options: ChannelOptions,
		password: Secret,
	},
	JoinChannel {
		channel_id: Vec<u8>,
		/// A nearby listed channel's name, when no id or invite is given.
		name: String,
		password: Secret,
		invite: Secret,
	},
	LeaveChannel {
		channel_id: Vec<u8>,
	},
	/// Mint an invite; the token comes back in [`Outcome::invite`].
	CreateInvite {
		channel_id: Vec<u8>,
		ttl_seconds: u32,
		uses: u32,
	},
	RevokeMember {
		channel_id: Vec<u8>,
		fingerprint: Vec<u8>,
	},
	SetPrivacy {
		inbound: Option<Inbound>,
		advert: Option<Advert>,
	},
	/// Delete every call history entry on this device.
	ClearCallHistory,
	/// Open the microphone for a level-only test (nothing is sent or played).
	StartMicTest,
	/// Close the microphone test.
	StopMicTest,
}

/// What a finished command yields.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct Outcome {
	/// Lease generation, when the command acquired call control.
	pub generation: Option<u64>,
	/// A freshly minted invite token; a secret, shown once and never logged.
	pub invite: Option<Secret>,
}

/// How the engine treated one key of a settings change.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SettingOutcome {
	/// In effect now.
	AppliedLive,
	/// Stored; read at the next start of the daemon (or the app using it).
	SavedNeedsRestart,
	/// Not stored; see the reason.
	Rejected,
}

/// The engine's answer for one key.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SettingResult {
	pub key: String,
	pub outcome: SettingOutcome,
	/// Why the key was rejected, or why it needs a restart. May be empty.
	pub reason: String,
}

#[async_trait]
pub trait Operations: Send + Sync {
	async fn run(&self, command: Command) -> Result<Outcome, EngineError>;

	/// Addresses and connection string to show or copy.
	async fn connection_info(&self) -> Result<ConnectionView, EngineError> {
		Err(unsupported())
	}

	/// The canonical PNG for an avatar hash.
	async fn avatar(&self, _sha256: Vec<u8>) -> Result<Vec<u8>, EngineError> {
		Err(unsupported())
	}

	/// The newest call history entries (`ListCallHistory`), newest first.
	async fn call_history(&self) -> Result<Vec<crate::model::HistoryEntry>, EngineError> {
		Err(unsupported())
	}

	/// Every preference as flat `section.key` text (`GetSettings`).
	async fn get_settings(
		&self,
	) -> Result<std::collections::BTreeMap<String, String>, EngineError> {
		Err(unsupported())
	}

	/// Bytes in use next to the limits that bound them, keyed by the limit's preference key
	/// (`GetSettings`). Empty when the engine does not report them.
	async fn limit_usage(&self) -> Result<std::collections::BTreeMap<String, u64>, EngineError> {
		Ok(std::collections::BTreeMap::new())
	}

	/// Opens one call's live statistics (`WatchCallStats`, one sample per second). Open it only
	/// while the debug panel is visible and drop it when the panel closes.
	async fn watch_call_stats(
		&self,
		_call_id: Vec<u8>,
	) -> Result<Box<dyn CallStatsSource>, EngineError> {
		Err(unsupported())
	}

	/// Change preferences (`SetSettings`); one result per key.
	async fn set_settings(
		&self,
		_values: Vec<(String, String)>,
	) -> Result<Vec<SettingResult>, EngineError> {
		Err(unsupported())
	}
}

fn unsupported() -> EngineError {
	EngineError::Rejected {
		code: "UNSUPPORTED".into(),
		message: tr!("err-unsupported").into(),
	}
}

#[async_trait]
pub trait EventSource: Send {
	/// Next validated item; `Ok(None)` when the engine closed the stream.
	async fn next(&mut self) -> Result<Option<WatchItem>, EngineError>;
}

/// A stream of call statistics samples; `Ok(None)` when the engine closed it.
#[async_trait]
pub trait CallStatsSource: Send {
	async fn next(&mut self) -> Result<Option<crate::model::CallStats>, EngineError>;
}

#[async_trait]
pub trait TelemetrySource: Send {
	async fn next(&mut self) -> Result<Option<pb::TelemetrySnapshot>, EngineError>;
}

/// A registered session with its first snapshot and live streams.
pub struct Connection {
	pub info: pb::EngineInfo,
	pub client_id: Vec<u8>,
	pub snapshot: pb::Snapshot,
	pub watch: Box<dyn EventSource>,
	pub telemetry: Option<Box<dyn TelemetrySource>>,
	pub ops: Arc<dyn Operations>,
}

#[async_trait]
pub trait Engine: Send + Sync + 'static {
	async fn connect(&self) -> Result<Connection, EngineError>;
}
