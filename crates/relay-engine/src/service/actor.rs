//! The control actor: the single task that owns [`relay_core::Engine`].
//!
//! Inputs arrive as messages, time arrives as ticks scheduled from
//! `next_deadline()`, and every domain effect leaves through the ports. Gate
//! updates are published (arc-swap) before an answer is sent.

use std::collections::VecDeque;
use std::future::pending;
use std::time::Duration;

use relay_api::pb::{StateEvent, state_event};
use relay_core::{
	Cursor, Effect, Engine, Event, Incarnation, Input, MonoTime, Outcome, PeerEvent, QueueFull,
	Submitted, SystemEvent, Watch,
};
use tokio::sync::mpsc;
use tokio::time::{Instant, sleep_until};

use super::convert::{events_of, settings_to_pb};
use super::directory::Directory;
use super::feed::Feed;
use super::gates::GatePublisher;
use super::handle::{Applied, Msg};
use super::ledger::Ledger;
use super::ports::Ports;

/// Upper bound on feedback inputs generated by one external input.
const FEEDBACK_BUDGET: usize = 64;

pub(crate) struct Actor {
	pub(super) engine: Engine,
	pub(super) ports: Ports,
	pub(super) gates: GatePublisher,
	pub(super) feed: Feed,
	pub(super) directory: Directory,
	pub(super) ledger: Ledger,
	pub(super) incarnation: [u8; 16],
	/// The client whose microphone test is running, if any.
	pub(super) mic_test_owner: Option<relay_core::ClientId>,
	cursor: Cursor,
	origin: Instant,
	inbox: mpsc::Receiver<Msg>,
	feedback: VecDeque<Input>,
}

impl Actor {
	#[allow(clippy::too_many_arguments)]
	pub(crate) fn new(
		engine: Engine,
		ports: Ports,
		gates: GatePublisher,
		feed: Feed,
		directory: Directory,
		ledger: Ledger,
		incarnation: [u8; 16],
		inbox: mpsc::Receiver<Msg>,
	) -> Self {
		let cursor = Cursor {
			incarnation: Incarnation::from_u128(u128::from_be_bytes(incarnation)),
			revision: relay_core::Revision::ZERO,
		};
		Self {
			engine,
			ports,
			gates,
			feed,
			directory,
			ledger,
			incarnation,
			mic_test_owner: None,
			cursor,
			origin: Instant::now(),
			inbox,
			feedback: VecDeque::new(),
		}
	}

	pub(crate) async fn run(mut self) {
		loop {
			let deadline = self.next_wakeup();
			tokio::select! {
				msg = self.inbox.recv() => match msg {
					None | Some(Msg::Shutdown) => break,
					Some(msg) => self.handle(msg),
				},
				() = wait_until(deadline) => {
					let _ = self.run_input(Input::Tick);
				}
			}
		}
		self.shut_down();
	}

	pub(super) fn now(&self) -> MonoTime {
		let millis = u64::try_from(self.origin.elapsed().as_millis()).unwrap_or(u64::MAX);
		MonoTime::from_millis(millis)
	}

	fn next_wakeup(&self) -> Option<Instant> {
		let at = self.engine.state().next_deadline()?;
		Some(self.origin + Duration::from_millis(at.as_millis()))
	}

	fn handle(&mut self, msg: Msg) {
		match msg {
			Msg::Submit { request, reply } => {
				let answer = self
					.run_input(Input::Client(request))
					.map(|outcome| self.applied(outcome))
					.map_err(|QueueFull| super::error::ServiceError::Busy);
				let _ = reply.send(answer);
			}
			Msg::Input(input) => {
				if let Input::Disconnected(client) = &input {
					self.ledger.purge_client(*client);
					if self.mic_test_owner == Some(*client) {
						self.mic_test_owner = None;
						let _ = self.ports.media.stop_mic_test();
					}
				}
				let _ = self.run_input(input);
			}
			Msg::Service {
				client,
				operation,
				print,
				op,
				reply,
			} => {
				let _ = reply.send(self.service_op(client, operation, print, op));
			}
			Msg::Snapshot(reply) => {
				let _ = reply.send(self.snapshot());
			}
			Msg::Operation {
				client,
				operation,
				reply,
			} => {
				let _ = reply.send(self.operation(client, operation));
			}
			Msg::Subscribe { after, reply } => {
				let _ = reply.send(self.subscribe(after));
			}
			Msg::Peers(peers) => {
				let events = self.directory.set_peers(peers);
				self.publish(events);
			}
			Msg::Channels { view, reply } => {
				let events = self.directory.set_channels(view);
				self.publish(events);
				let _ = reply.send(self.feed.revision());
			}
			Msg::Devices(devices) => {
				let events = self.directory.set_devices(devices);
				self.publish(events);
			}
			Msg::Attention { peer, warning } => {
				let mut events = peer.map(|p| self.directory.flag(p)).unwrap_or_default();
				events.extend(self.directory.warn(warning));
				self.publish(events);
			}
			Msg::Shutdown => {}
		}
	}

	fn applied(&self, outcome: Outcome) -> Applied {
		Applied {
			result: outcome.result,
			revision: outcome.revision,
			duplicate: outcome.duplicate,
			api_revision: self.feed.revision(),
			at: self.now(),
		}
	}

	/// Applies an input, performs its effects, publishes its events and then
	/// settles whatever the effects fed back.
	fn run_input(&mut self, input: Input) -> Result<Outcome, QueueFull> {
		let outcome = self.apply(input)?;
		let mut budget = FEEDBACK_BUDGET;
		while budget > 0
			&& let Some(next) = self.feedback.pop_front()
		{
			budget -= 1;
			let _ = self.apply(next);
		}
		self.feedback.clear();
		Ok(outcome)
	}

	fn apply(&mut self, input: Input) -> Result<Outcome, QueueFull> {
		let now = self.now();
		let mut outcomes = Vec::new();
		if let Submitted::Applied(outcome) = self.engine.submit(input, now)? {
			outcomes.push(*outcome);
		}
		outcomes.extend(self.engine.drain(now));
		for outcome in &outcomes {
			self.perform(&outcome.effects);
		}
		self.sync_feed();
		// A queued input is always drained last, so the final outcome is ours.
		outcomes.pop().ok_or(QueueFull)
	}

	fn perform(&mut self, effects: &[Effect]) {
		for effect in effects {
			match *effect {
				Effect::GateUpdate { gate, revision } => self.gates.publish(gate, revision),
				Effect::ReceiveMix(mix) => self.ports.media.set_receive_mix(mix),
				Effect::OpenCapture { generation } => {
					if let Err(error) = self.ports.media.open_capture(generation) {
						tracing::warn!(%error, "capture could not be opened");
						self.feedback
							.push_back(Input::System(SystemEvent::CaptureFailed { generation }));
					}
				}
				Effect::CloseCapture { generation } => self.ports.media.close_capture(generation),
				Effect::EnsureLink { peer } => {
					if let Err(error) = self.ports.peers.ensure_link(peer) {
						tracing::warn!(%error, %peer, "peer link could not be requested");
						self.feedback
							.push_back(Input::Peer(PeerEvent::LinkDown(peer)));
					}
				}
				Effect::Peer { peer, message } => {
					if let Err(error) = self.ports.peers.send(peer, message) {
						tracing::warn!(%error, %peer, "peer message not sent");
					}
				}
				Effect::PrepareMedia { call, session } => {
					if let Err(error) = self.ports.media.prepare_media(call, session) {
						tracing::warn!(%error, %call, "media could not be prepared");
					}
				}
				Effect::StopMedia { call, session } => self.ports.media.stop_media(call, session),
			}
		}
	}

	/// Converts new domain events into API events, keeping one gapless sequence.
	fn sync_feed(&mut self) {
		match self.engine.state().watch(self.cursor) {
			Watch::Events(items) => {
				for item in items {
					if let Event::CallForgotten(id) = &item.event {
						self.gates.forget(*id);
					}
					let next = self.feed.revision() + 1;
					let events = events_of(&item.event, next, &mut self.directory);
					self.publish(events);
					self.cursor.revision = item.revision;
				}
			}
			Watch::Resync(snapshot) => {
				tracing::error!("domain event window lost; asking watchers to resync");
				self.cursor = snapshot.cursor();
				self.feed.reset();
			}
		}
	}

	pub(super) fn publish(&mut self, events: Vec<StateEvent>) {
		for event in events {
			self.feed.push(event);
		}
	}

	/// Announces the current engine-wide settings to watchers.
	pub(super) fn publish_settings(&mut self) {
		let global = self.engine.state().snapshot().global;
		let settings = settings_to_pb(&global, &self.directory.aux);
		self.publish(vec![StateEvent {
			event: Some(state_event::Event::Settings(settings)),
		}]);
	}

	/// Detaches every client and stops every live call before exiting.
	fn shut_down(&mut self) {
		let _ = self.ports.media.stop_mic_test();
		let snapshot = self.engine.state().snapshot();
		for client in snapshot.clients {
			let _ = self.apply(Input::Disconnected(client));
		}
		for call in snapshot.calls.values().filter(|c| !c.state.is_terminal()) {
			self.ports.media.stop_media(call.id, call.session);
			let _ = self.ports.peers.send(
				call.peer,
				relay_core::PeerMessage::End {
					call: call.id,
					session: call.session,
				},
			);
		}
	}
}

async fn wait_until(deadline: Option<Instant>) {
	match deadline {
		Some(at) => sleep_until(at).await,
		None => pending().await,
	}
}
