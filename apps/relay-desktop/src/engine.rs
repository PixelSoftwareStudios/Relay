//! Port between the desktop host and the engine. The real adapter wraps
//! `relay_api::RelayClient`; tests plug in a fake.

use std::sync::Arc;

use async_trait::async_trait;
use relay_api::WatchItem;
use relay_api::pb;

use crate::model::Mode;

#[derive(Debug, thiserror::Error)]
pub enum EngineError {
	/// Daemon not reachable (not running, socket missing, connection refused).
	#[error("the Relay daemon is not reachable: {0}")]
	Unavailable(String),
	/// The engine refused or failed the request.
	#[error("{message}")]
	Rejected { code: String, message: String },
	#[error("the engine did not answer in time")]
	Timeout,
	/// The connection broke or violated the protocol; reconnect and resync.
	#[error("connection problem: {0}")]
	Broken(String),
}

/// Everything the UI may ask the engine to do. Ids are raw bytes already
/// validated by the controller; operation ids are generated by the adapter.
#[derive(Debug, Clone, PartialEq)]
pub enum Command {
	StartCall {
		peer_id: Vec<u8>,
	},
	AcquireController {
		call_id: Vec<u8>,
	},
	AcceptCall {
		call_id: Vec<u8>,
		generation: u64,
	},
	DeclineCall {
		call_id: Vec<u8>,
		generation: u64,
	},
	EndCall {
		call_id: Vec<u8>,
		generation: u64,
	},
	SetTransmit {
		call_id: Vec<u8>,
		generation: u64,
		mode: Mode,
		consent: bool,
	},
	SetCallControls {
		call_id: Vec<u8>,
		generation: u64,
		muted: Option<bool>,
		deafened: Option<bool>,
		receive_gain: Option<f32>,
	},
	SetGlobalControls {
		muted: Option<bool>,
		deafened: Option<bool>,
		microphone_gain: Option<f32>,
		playback_gain: Option<f32>,
	},
	SelectDevices {
		input_id: String,
		output_id: String,
	},
	SetProfile {
		display_name: String,
	},
	UploadAvatar {
		bytes: Vec<u8>,
		media_type: String,
	},
}

/// What a finished command yields.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct Outcome {
	/// Lease generation, when the command acquired call control.
	pub generation: Option<u64>,
}

#[async_trait]
pub trait Operations: Send + Sync {
	async fn run(&self, command: Command) -> Result<Outcome, EngineError>;
}

#[async_trait]
pub trait EventSource: Send {
	/// Next validated item; `Ok(None)` when the engine closed the stream.
	async fn next(&mut self) -> Result<Option<WatchItem>, EngineError>;
}

#[async_trait]
pub trait TelemetrySource: Send {
	async fn next(&mut self) -> Result<Option<pb::TelemetrySnapshot>, EngineError>;
}

/// A registered session with its first snapshot and live streams.
pub struct Connection {
	pub info: pb::EngineInfo,
	pub client_id: Vec<u8>,
	pub snapshot: pb::Snapshot,
	pub watch: Box<dyn EventSource>,
	pub telemetry: Option<Box<dyn TelemetrySource>>,
	pub ops: Arc<dyn Operations>,
}

#[async_trait]
pub trait Engine: Send + Sync + 'static {
	async fn connect(&self) -> Result<Connection, EngineError>;
}
